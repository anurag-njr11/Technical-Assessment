// npm run eval -- [--preset free|local|openrouter] [--limit N] [--profiles expert,vague]
//
// Grades the synthetic golden set and the adversarial suite with real models,
// writes evals/results/<date>-<preset>.json and prepends a summary to
// EVALUATION.md. Keys come from the environment (e.g. `node --env-file=.env.eval`):
// GEMINI_API_KEY, GROQ_API_KEY, OPENROUTER_API_KEY, OLLAMA_BASE_URL.

import { mkdirSync, readFileSync, writeFileSync, existsSync } from "node:fs"
import { GOLDEN } from "./golden"
import { evaluate, toMarkdown } from "./evaluate"
import { PROMPT_VERSION, getPanel, liveAsker, preset } from "../convex/judges"
import type { Trace } from "../convex/judges"

const arg = (name: string) => {
  const i = process.argv.indexOf(`--${name}`)
  return i > 0 ? process.argv[i + 1] : undefined
}

if (arg("preset")) process.env.JUDGE_PRESET = arg("preset")
const profiles = arg("profiles")?.split(",")
const cases = GOLDEN.filter((c) => !profiles || profiles.includes(c.profile)).slice(0, Number(arg("limit") ?? Infinity))

const traces: Trace[] = []
const panel = getPanel()
console.log(`Preset ${preset()}: ${panel.map((j) => `${j.name} ${j.primary.provider ?? ""}:${j.primary.model} / ${j.fallback.model}`).join(" · ")}`)
console.log(`Grading ${cases.length} golden reviews + the adversarial suite…`)

const report = await evaluate(cases, liveAsker(traces), panel, traces, (done, total) => process.stdout.write(`\r  ${done}/${total}`))
process.stdout.write("\n")

const date = new Date().toISOString().slice(0, 10)
mkdirSync("evals/results", { recursive: true })
const file = `evals/results/${date}-${preset()}.json`
writeFileSync(file, JSON.stringify({ date, preset: preset(), promptVersion: PROMPT_VERSION, panel, report }, null, 2))

const md = toMarkdown(report, { date, preset: preset(), promptVersion: PROMPT_VERSION })
const HEADER = "<!-- runs below are generated by `npm run eval`; newest first -->\n"
const doc = existsSync("EVALUATION.md") ? readFileSync("EVALUATION.md", "utf8") : HEADER
const at = doc.indexOf(HEADER)
writeFileSync("EVALUATION.md", at >= 0 ? doc.slice(0, at + HEADER.length) + "\n" + md + doc.slice(at + HEADER.length) : `${doc}\n${HEADER}\n${md}`)
console.log(md)
console.log(`Saved ${file} and updated EVALUATION.md`)
